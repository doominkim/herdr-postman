var postmanRotationFrames = buildPostmanRotationFrames()

func buildPostmanRotationFrames() []string {
	mask := strings.Split(postmanFigure, "\n")
	frames := make([]string, 48)
	dots := []struct{ x, y, bit int }{{0, 0, 0}, {0, 1, 1}, {0, 2, 2}, {1, 0, 3}, {1, 1, 4}, {1, 2, 5}, {0, 3, 6}, {1, 3, 7}}
	for frame := range frames {
		angle := float64(frame) * 2 * math.Pi / float64(len(frames))
		sin, cos := math.Sincos(angle)
		ink := func(px, py int) bool {
			x, y := (float64(px)+.5-40)/40, (float64(py)+.5-32)/32
			radius := math.Hypot(x, y)
			if radius > .995 {
				return false
			}
			if radius > .95 {
				return true
			}
			// Inverse rotation keeps the figure centered; enlarge it slightly for clarity.
			sx, sy := (cos*x+sin*y)/1.08, (-sin*x+cos*y)/1.08
			mx, my := int(math.Floor((sx+1)*32)), int(math.Floor((sy+1)*32))
			return mx >= 0 && mx < 64 && my >= 0 && my < 64 && mask[my][mx] == '#'
		}
		var out strings.Builder
		for y := 0; y < 64; y += 4 {
			for x := 0; x < 80; x += 2 {
				bits := 0
				for _, d := range dots {
					if ink(x+d.x, y+d.y) {
						bits |= 1 << d.bit
					}
				}
				if bits == 0 {
					out.WriteByte(' ')
				} else {
					out.WriteRune(rune(0x2800 + bits))
				}
			}
			if y < 60 {
				out.WriteByte('\n')
			}
		}
		frames[frame] = out.String()
	}
	return frames
}

func postmanLoadingScreen(ctx t.BuildContext, status, frame string) t.Widget {
	centered := func(text string, color t.Color, bold bool) t.Widget {
		return t.Text{Content: text, TextAlign: t.TextAlignCenter, Wrap: t.WrapSoft,
			Style: t.Style{Width: t.Flex(1), ForegroundColor: color, Bold: bold}}
	}
	return t.Column{
		Style:     t.Style{Width: t.Flex(1), Height: t.Flex(1), BackgroundColor: ctx.Theme().Background},
		MainAlign: t.MainAxisCenter, CrossAlign: t.CrossAxisCenter,
		Children: []t.Widget{
			t.Text{Content: frame, Style: t.Style{Width: t.Cells(40), Height: t.Cells(16), ForegroundColor: t.Hex("#FF6C37")}},
			centered("", ctx.Theme().Text, false),
			centered("herdr-postman", t.Hex("#FF6C37"), true),
			centered("Unofficial terminal client.", ctx.Theme().TextMuted, false),
			centered("Not affiliated with or endorsed by Postman.", ctx.Theme().TextMuted, false),
			centered("", ctx.Theme().Text, false),
			centered(status, ctx.Theme().Text, false),
			centered("Esc to cancel · 60s timeout", ctx.Theme().TextMuted, false),
		},
	}
}
